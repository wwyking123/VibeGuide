#!/usr/bin/env node
// Copies the real sidebar styles out of the plugin source, so the video shows the sidebar exactly as it ships.
import { readFileSync, writeFileSync } from 'node:fs';

const grab = file => {
  const found = readFileSync(new URL(`../src/client/${file}`, import.meta.url), 'utf8').match(/const styles = `([\s\S]*?)`;/);
  if (!found) throw new Error(`No styles found in ${file}`);
  return found[1].trim();
};
writeFileSync(new URL('sidebar.css', import.meta.url),
  `/* Generated by sync-sidebar.mjs from src/client/index.tsx and selection-ask.tsx. Do not edit. */\n${grab('index.tsx')}\n${grab('selection-ask.tsx')}\n`);
